describe('writeDownload', () => {
  it('is atomic and refuses to overwrite without the flag', () => {
    const dir = mkdtempSync(join(tmpdir(), 'coinpay-dl-'));
    const target = join(dir, 'out.csv');
    writeDownload(target, Buffer.from('a'));
    expect(() => writeDownload(target, Buffer.from('b'))).toThrow(CliExit);
    writeDownload(target, Buffer.from('b'), { overwrite: true });
    expect(readFileSync(target, 'utf8')).toBe('b');
    expect(existsSync(join(dir, 'out.csv.tmp'))).toBe(false);
  });
});

