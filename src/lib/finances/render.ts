export function pdfMaxRows(): number {
  const n = Number(process.env.FINANCES_PDF_MAX_ROWS ?? 20_000);
  return Number.isFinite(n) && n > 0 ? n : 20_000;
}

type PdfLike = import('jspdf').jsPDF;
