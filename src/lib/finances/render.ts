const CSV_COLUMNS = [
  'section',
  'account_name',
  'institution',
  'currency',
  'posted',
  'transacted_at',
  'amount',
  'description',
  'payee',
  'memo',
  'category',
  'mcc',
  'pending',
  'external_id',
  'account_id',
  'transaction_id',
] as const;

/**
 * Quote a text field for CSV and neutralise spreadsheet formula prefixes.
 *
 * A description beginning with `=`, `+`, `-`, `@`, or a tab/CR is executed
 * as a formula by Excel and LibreOffice when the file is opened. Prefixing a
 * single quote makes it text. Amounts are emitted by `csvNumber`, which is
 * why a negative amount is unaffected.
 */
export function csvText(value: string | null | undefined): string {
  if (value === null || value === undefined) return '';
  let text = String(value);
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  if (/[",\r\n]/.test(text)) text = `"${text.replace(/"/g, '""')}"`;
  return text;
}

function csvNumber(value: ExactAmount | null): string {
  return value ?? '';
}

export function renderCsv(ds: ReportDataset): string {
  const accountById = new Map(ds.accounts.map((a) => [a.id, a]));
  const lines: string[] = [];
  lines.push(`# ${GENERATED_BY_NOTICE}`);
  lines.push(`# Report ${ds.report.id} revision ${ds.report.revision}; period ${ds.report.periodLabel} (${ds.report.timezone}); generated ${ds.report.generatedAt}`);
  lines.push(`# Provider coverage: ${ds.coverage.provider_coverage}; local export complete: ${ds.coverage.local_export_complete}; posted rows: ${ds.posted.length}; pending rows: ${ds.pending.length}`);
  lines.push(CSV_COLUMNS.join(','));

  const emit = (section: 'posted' | 'pending', row: ReportRow) => {
    const account = accountById.get(row.accountId);
    lines.push(
      [
        section,
        csvText(account?.name ?? ''),
        csvText(account?.orgName ?? ''),
        csvText(account?.currency ?? ''),
        csvText(row.posted),
        csvText(row.transactedAt),
        csvNumber(row.amount),
        csvText(row.description),
        csvText(row.payee),
        csvText(row.memo),
        csvText(row.category),
        csvText(row.mcc),
        section === 'pending' ? 'true' : 'false',
        csvText(row.externalId),
        csvText(row.accountId),
        csvText(row.id),
      ].join(','),
    );
  };
  for (const row of ds.posted) emit('posted', row);
  for (const row of ds.pending) emit('pending', row);
  return lines.join('\r\n') + '\r\n';
}

