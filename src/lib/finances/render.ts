  /** The balance the provider last reported, and when. Not a period balance. */
  currentBalance: ExactAmount | null;
  currentBalanceAsOf: string | null;
  availableBalance: ExactAmount | null;
  /** Period boundaries are unknown unless a statement supplies them. */
  openingBalance: ExactAmount | null;
