import { formatFixed, displayDecimalsFor, type ExactAmount } from './decimal';
import type { AccountCoverage, ProviderCoverage } from './coverage';

/**
 * Report artifacts, all derived from one canonical dataset.
 *
 * The dataset is what the report IS; CSV, HTML and PDF are views of it. No
 * renderer computes a total — every figure it prints was summed exactly
 * upstream (in Postgres and re-checked in `decimal.ts`) and arrives here as
 * a decimal string. A renderer that disagreed with the JSON would be a bug
 * in the renderer, never a second opinion.
 *
 * This module has no server-only import so the text formats can be tested
 * as pure functions; the PDF renderer loads jsPDF lazily.
 */

export const RENDERER_VERSION = 'finance-report-renderer/1.0.0';
export const DATASET_SCHEMA = 'coinpay.finance-report/1';

export const GENERATED_BY_NOTICE =
  'Generated by CoinPay from imported account data; not an institution-issued statement.';

export interface ReportRow {
  id: string;
  accountId: string;
  externalId: string;
  posted: string | null;
  transactedAt: string | null;
  amount: ExactAmount;
  description: string | null;
  payee: string | null;
  memo: string | null;
  mcc: string | null;
  category: string | null;
  revision: number;
}

export interface ReportAccount {
  id: string;
  name: string;
  orgName: string | null;
  currency: string;
  kind: string;
  scope: string;
  isHidden: boolean;
  identityState: string;
  /** The balance the provider last reported, and when. Not a period balance. */
  currentBalance: ExactAmount | null;
  currentBalanceAsOf: string | null;
  availableBalance: ExactAmount | null;
  /** Period boundaries are unknown unless a statement supplies them. */
  openingBalance: ExactAmount | null;
  closingBalance: ExactAmount | null;
  balanceProvenance: 'unavailable' | 'user_statement_entry' | 'provider_snapshot';
}

export interface CurrencyTotals {
  currency: string;
  credits: ExactAmount;
  debits: ExactAmount;
  net: ExactAmount;
  rows: number;
}

export interface AccountTotals {
  accountId: string;
  credits: ExactAmount;
  debits: ExactAmount;
  net: ExactAmount;
  rows: number;
}

export interface ReportDataset {
  schema: typeof DATASET_SCHEMA;
  report: {
    id: string;
    revision: number;
    merchantId: string;
    periodKind: string;
    periodSelector: string;
    periodLabel: string;
    timezone: string;
    requestedStart: string;
    requestedEnd: string;
    effectiveEnd: string;
    periodToDate: boolean;
    cutoff: string;
    scope: string;
    includeHidden: boolean;
    includePending: boolean;
    generatedAt: string;
    snapshotAt: string;
    rendererVersion: string;
  };
  accounts: ReportAccount[];
  posted: ReportRow[];
  pending: ReportRow[];
  totals: CurrencyTotals[];
  accountTotals: AccountTotals[];
  coverage: {
    local_export_complete: boolean;
    provider_coverage: ProviderCoverage;
    reconciliation_status: string;
    accounts: AccountCoverage[];
    warnings: string[];
    explanation: string;
  };
  statements: Array<{ id: string; accountId: string; institutionLabel: string | null; periodStart: string; periodEnd: string }>;
  disclaimers: string[];
}

/** Stable JSON: keys sorted, no whitespace. The hash is over this. */
export function canonicalJson(value: unknown): string {
  return JSON.stringify(sortKeys(value));
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(value as Record<string, unknown>).sort()) {
      out[key] = sortKeys((value as Record<string, unknown>)[key]);
    }
    return out;
  }
  return value;
}

export function coverageExplanation(coverage: ProviderCoverage, periodToDate: boolean): string {
  const base =
    coverage === 'available_window_fetched'
      ? 'Every part of this period was fetched from the provider at least once. That is what the provider made available; it is not independent verification that the institution supplied complete history.'
      : coverage === 'partial'
        ? 'Part of this period was never fetched from the provider, or a fetch was cut short. History may be incomplete.'
        : 'No part of this period is known to have been fetched from the provider. The rows below are whatever was already imported; history may be incomplete.';
  return periodToDate ? `${base} The period is still running (period to date).` : base;
}

