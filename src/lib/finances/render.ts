const PAGE_W = 612;
const PAGE_H = 792;

/**
 * The executive summary pages: stat tiles, the plain-English highlights,
 * the five charts and the month table. Returns the y to continue from.
 */
function renderSummaryPdf(doc: PdfLike, autoTable: AutoTableFn, s: ReportSummary, multiCurrency: boolean, startY: number, margin: number): number {
  const c = s.currency;
  const width = PAGE_W - margin * 2;
  let y = startY;
  const ensure = (h: number) => {
    if (y + h > PAGE_H - 40) {
      doc.addPage();
      y = margin;
    }
  };

  ensure(120);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(CHART_COLORS.text);
  doc.text(`Executive summary${multiCurrency ? ` (${c})` : ''}`, margin, y + 12);
  y += 18;
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(CHART_COLORS.muted);
  const intro = `Money in and money out exclude transfers between the owner's own accounts and card payments, so nothing is counted twice. Every figure is ${c}; nothing is converted.${s.estimate ? ' Figures marked estimated are an extrapolation, not bank data.' : ''}`;
  const introLines = doc.splitTextToSize(intro, width) as string[];
  doc.text(introLines, margin, y + 8);
  y += 10 * introLines.length + 8;

  // --- stat tiles -----------------------------------------------------------
  const tiles: Array<[string, string, string]> = [
    ['Money in', formatMoney(s.incomeWithEstimate, c), s.estimate ? 'observed + estimated' : 'observed'],
    ['Money out', formatMoney(s.spendingWithEstimate, c), s.estimate ? 'observed + estimated' : 'observed'],
    ['Net', formatMoney(s.netWithEstimate, c), s.monthsSpendingExceededIncome > 0 ? `out exceeded in ${s.monthsSpendingExceededIncome} of ${s.months.length} months` : 'income covered spending every month'],
    ['Average per month', `${formatMoney(s.monthlyMeanIncome, c)} in`, `${formatMoney(s.monthlyMeanSpending, c)} out, over ${s.observedDays} observed days`],
    ['Cash on hand', formatMoney(s.cashOnHand, c), `as of ${(s.balancesAsOf ?? 'last sync').slice(0, 10)}${!isZeroText(s.owed) ? `; ${formatMoney(s.owed, c)} owed` : ''}`],
  ];
  const gap = 8;
  const tileW = (width - gap * (tiles.length - 1)) / tiles.length;
  const tileH = 48;
  tiles.forEach(([label, value, sub], i) => {
    const x = margin + i * (tileW + gap);
    doc.setFillColor('#fafaf9');
    doc.setDrawColor(CHART_COLORS.grid);
    doc.setLineWidth(0.75);
    doc.roundedRect(x, y, tileW, tileH, 4, 4, 'FD');
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(CHART_COLORS.muted);
    doc.text(label, x + 6, y + 11);
    doc.setFontSize(value.length > 14 ? 9 : 11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(CHART_COLORS.text);
    doc.text(value, x + 6, y + 25);
    doc.setFontSize(6);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(CHART_COLORS.muted);
    const subLines = (doc.splitTextToSize(sub, tileW - 12) as string[]).slice(0, 2);
    doc.text(subLines, x + 6, y + 34);
  });
  y += tileH + 10;

  // --- highlights -----------------------------------------------------------
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(CHART_COLORS.text);
  for (const h of s.highlights) {
    const lines = doc.splitTextToSize(h, width - 12) as string[];
    ensure(11 * lines.length + 2);
    doc.text('•', margin + 2, y + 9);
    doc.text(lines, margin + 12, y + 9);
    y += 11 * lines.length + 2;
  }
  y += 6;

  // --- charts ---------------------------------------------------------------
  const cv = new PdfCanvas(doc);
  const colW = (width - 16) / 2;
  const chartFrame = (box: Box) => {
    doc.setDrawColor(CHART_COLORS.grid);
    doc.setLineWidth(0.75);
    doc.roundedRect(box.x - 6, box.y - 6, box.w + 12, box.h + 12, 4, 4, 'S');
  };
  const row = (left: (b: Box) => void, right: (b: Box) => void, h: number) => {
    ensure(h + 16);
    const a: Box = { x: margin + 6, y: y + 6, w: colW - 12, h: h - 12 };
    const b: Box = { x: margin + colW + 16 + 6, y: y + 6, w: colW - 12, h: h - 12 };
    chartFrame(a);
    chartFrame(b);
    left(a);
    right(b);
    y += h + 12;
  };
  row(
    (b) => drawMonthlyFlows(cv, b, s.months, c),
    (b) => drawCumulativeNet(cv, b, s.months, c),
    180,
  );
  const rankedH = 44 + 18 * Math.max(3, Math.max(s.spendingByCategory.length, s.incomeBySource.length));
  row(
    (b) => drawRankedBars(cv, b, s.spendingByCategory, c, 'Where the money went', CHART_COLORS.spending),
    (b) => drawRankedBars(cv, b, s.incomeBySource, c, 'Where the money came from', CHART_COLORS.income),
    rankedH,
  );
  const balancesH = 56 + 16 * Math.max(3, s.balances.length);
  ensure(balancesH + 16);
  const full: Box = { x: margin + 6, y: y + 6, w: width - 12, h: balancesH - 12 };
  chartFrame(full);
  drawBalances(cv, full, s.balances, c);
  y += balancesH + 12;

  // --- month table ----------------------------------------------------------
  doc.setTextColor(0);
  autoTable(doc, {
    startY: y,
    head: [['Month', 'Money in', 'Money out', 'Net', 'Running total', 'Transfers in / out', 'Rows']],
    body: s.months.length
      ? s.months.map((m) => [
          `${m.label}${m.estimatedDays > 0 ? ` (${m.estimatedDays === m.days ? 'estimated' : `${m.estimatedDays} of ${m.days} days est.`})` : ''}`,
          formatMoney(m.incomeWithEstimate, c),
          formatMoney(m.spendingWithEstimate, c),
          formatMoney(m.netWithEstimate, c),
          formatMoney(m.cumulativeNet, c),
          `${formatMoney(m.transfersIn, c)} / ${formatMoney(m.transfersOut, c)}`,
          String(m.rows),
        ])
      : [['No months in this period', '', '', '', '', '', '']],
    foot: s.estimate ? [[{ content: s.estimate.basis, colSpan: 7, styles: { fontSize: 6.5, textColor: [82, 81, 78], fontStyle: 'italic' } }]] : undefined,
    showFoot: 'lastPage',
    styles: { fontSize: 7.5, cellPadding: 2.5 },
    headStyles: { fillColor: [235, 235, 235], textColor: 20 },
    footStyles: { fillColor: [255, 255, 255] },
    columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' }, 6: { halign: 'right' } },
    margin: { left: margin, right: margin },
  });
  return (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 18;
}

export async function renderPdf(ds: ReportDataset): Promise<Buffer> {
  const { jsPDF } = await import('jspdf');
  const autoTable = (await import('jspdf-autotable')).default;
  const tz = ds.report.timezone;
  const accountById = new Map(ds.accounts.map((a) => [a.id, a]));

  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'letter', compress: true });
  // Deterministic metadata: two renders of one dataset should agree, so the
  // creation date comes from the dataset and the file id from the report
  // identity rather than jsPDF's random default.
  doc.setCreationDate(new Date(ds.report.generatedAt));
  const { createHash } = await import('crypto');
  doc.setFileId(createHash('md5').update(`${ds.report.id}:${ds.report.revision}:${ds.report.generatedAt}`).digest('hex').toUpperCase());
  doc.setProperties({
    title: `${ds.report.periodLabel} activity report`,
    subject: GENERATED_BY_NOTICE,
    creator: RENDERER_VERSION,
  });

  const margin = 40;
  let y = margin;
  doc.setFontSize(16);
  doc.text(`${ds.report.periodKind === 'quarter' ? 'Quarterly' : ds.report.periodKind === 'month' ? 'Monthly' : 'Custom period'} activity report: ${ds.report.periodLabel}`, margin, y);
  y += 18;
  doc.setFontSize(9);
  doc.setTextColor(80);
  const metaLines = [
    `Period ${ds.report.requestedStart} to ${ds.report.effectiveEnd} (exclusive), ${tz}. Scope ${ds.report.scope}. ${ds.accounts.length} account(s).`,
    `Report ${ds.report.id} revision ${ds.report.revision}. Generated ${ds.report.generatedAt}.`,
    ...(ds.report.periodToDate ? ['PERIOD TO DATE: the period is still running.'] : []),
    GENERATED_BY_NOTICE,
    ds.coverage.explanation,
    `Local export complete: ${ds.coverage.local_export_complete ? 'yes' : 'NO'}. Provider coverage: ${ds.coverage.provider_coverage}. Reconciliation: ${ds.coverage.reconciliation_status}.`,
  ];
  for (const line of metaLines) {
    const wrapped = doc.splitTextToSize(line, 612 - margin * 2) as string[];
    doc.text(wrapped, margin, y);
    y += 11 * wrapped.length;
  }
  if (ds.coverage.warnings.length) {
    doc.setTextColor(160, 20, 20);
    for (const w of ds.coverage.warnings.slice(0, 10)) {
      const wrapped = doc.splitTextToSize(`Warning: ${w}`, 612 - margin * 2) as string[];
      doc.text(wrapped, margin, y);
      y += 11 * wrapped.length;
    }
  }
  doc.setTextColor(0);
  y += 6;

  for (const s of ds.summary ?? []) {
    y = renderSummaryPdf(doc, autoTable, s, ds.summary.length > 1, y, margin);
  }

  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(CHART_COLORS.text);
  doc.text('Gross bank flows by currency', margin, y + 11);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(CHART_COLORS.muted);
  doc.text('Credits are money into the account and debits money out, transfers included. A credit is not automatically revenue and a debit is not automatically a deductible expense.', margin, y + 23, { maxWidth: 612 - margin * 2 });
  doc.setTextColor(0);
  y += 34;

  autoTable(doc, {
    startY: y,
    head: [['Currency', 'Credits', 'Debits', 'Net activity', 'Posted rows']],
    body: ds.totals.length
      ? ds.totals.map((t) => [t.currency, money(t.credits, t.currency), money(t.debits, t.currency), money(t.net, t.currency), String(t.rows)])
      : [['—', '0', '0', '0', '0']],
    styles: { fontSize: 8, cellPadding: 3 },
    headStyles: { fillColor: [235, 235, 235], textColor: 20 },
    columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' } },
    margin: { left: margin, right: margin },
  });

  if (ds.estimates.length) {
    const yEst = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
    autoTable(doc, {
      startY: yEst,
      head: [[{ content: 'ESTIMATED PERIOD (NOT OBSERVED): the institutions supplied no transactions for these days; figures are an extrapolation of the observed daily average, requested by the account owner. Not transactions.', colSpan: 6, styles: { halign: 'left', fillColor: [255, 240, 240], textColor: [160, 20, 20] } }], ['Currency', 'Estimated days', 'Daily mean credits / debits', 'Est. credits', 'Est. debits', 'Est. net']],
      body: ds.estimates.flatMap((e) => [
        [e.currency, `${e.gapStart} to ${e.gapEnd} (excl.), ${e.missingDays} days`, `${money(e.dailyMeanCredits, e.currency)} / ${money(e.dailyMeanDebits, e.currency)}`, money(e.estimatedCredits, e.currency), money(e.estimatedDebits, e.currency), money(e.estimatedNet, e.currency)],
        [{ content: e.basis, colSpan: 6, styles: { fontSize: 7, textColor: [90, 90, 90] } }],
      ]),
      styles: { fontSize: 8, cellPadding: 3 },
      headStyles: { fillColor: [235, 235, 235], textColor: 20 },
      columnStyles: { 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' } },
      margin: { left: margin, right: margin },
    });
    const yCombined = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;
    autoTable(doc, {
      startY: yCombined,
      head: [['Observed + estimated', 'Credits', 'Debits', 'Net']],
      body: ds.totalsWithEstimates.map((t) => [t.currency, money(t.credits, t.currency), money(t.debits, t.currency), money(t.net, t.currency)]),
      styles: { fontSize: 8, cellPadding: 3 },
      headStyles: { fillColor: [235, 235, 235], textColor: 20 },
      columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' } },
      margin: { left: margin, right: margin },
    });
  }

  const afterTotals = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
  autoTable(doc, {
    startY: afterTotals,
    head: [['Account', 'Cur.', 'Opening', 'Credits', 'Debits', 'Net', 'Closing', 'Current (as of)', 'Coverage']],
    body: ds.accounts.map((a) => {
      const t = ds.accountTotals.find((x) => x.accountId === a.id);
      const cov = ds.coverage.accounts.find((c) => c.accountId === a.id);
      return [
        `${a.name}\n${a.orgName ?? ''} · ${a.kind}`,
        a.currency,
        a.openingBalance === null ? 'unavailable' : money(a.openingBalance, a.currency),
        t ? money(t.credits, a.currency) : '0',
        t ? money(t.debits, a.currency) : '0',
        t ? money(t.net, a.currency) : '0',
        a.closingBalance === null ? 'unavailable' : money(a.closingBalance, a.currency),
        a.currentBalance === null ? '—' : `${money(a.currentBalance, a.currency)}\n${(a.currentBalanceAsOf ?? 'unknown').slice(0, 16)}`,
        cov?.coverage ?? 'unknown',
      ];
    }),
    styles: { fontSize: 7, cellPadding: 2 },
    headStyles: { fillColor: [235, 235, 235], textColor: 20 },
    columnStyles: { 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' }, 6: { halign: 'right' }, 7: { halign: 'right' } },
    margin: { left: margin, right: margin },
  });

  const ledger = (title: string, rows: ReportRow[]) => {
    const limit = pdfMaxRows();
    const shown = rows.slice(0, limit);
    const startY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
    autoTable(doc, {
      startY,
      head: [[{ content: `${title} (${rows.length}${rows.length > limit ? `; first ${limit} shown, all rows in CSV/JSON` : ''})`, colSpan: 6, styles: { halign: 'left', fillColor: [245, 245, 245] } }], ['Date', 'Account', 'Description', 'Category', 'Cur.', 'Amount']],
      body: shown.length
        ? shown.map((r) => {
            const a = accountById.get(r.accountId);
            const currency = a?.currency ?? '';
            return [
              dateOnly(r.posted ?? r.transactedAt, tz),
              a?.name ?? '',
              [r.description, r.payee].filter(Boolean).join(' · '),
              r.category ?? '',
              currency,
              money(r.amount, currency),
            ];
          })
        : [['', '', 'None', '', '', '']],
      styles: { fontSize: 7, cellPadding: 2, overflow: 'linebreak' },
      headStyles: { fillColor: [235, 235, 235], textColor: 20 },
      columnStyles: { 0: { cellWidth: 60 }, 1: { cellWidth: 90 }, 4: { cellWidth: 32 }, 5: { halign: 'right', cellWidth: 70 } },
      margin: { left: margin, right: margin },
      showHead: 'everyPage',
    });
  };
  ledger('Posted ledger', ds.posted);
  if (ds.report.includePending) ledger('Pending appendix (not included in totals)', ds.pending);

  const notesY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
  autoTable(doc, {
    startY: notesY,
    head: [['Notes']],
    body: ds.disclaimers.map((d) => [d]),
    styles: { fontSize: 7, cellPadding: 2 },
    headStyles: { fillColor: [235, 235, 235], textColor: 20 },
    margin: { left: margin, right: margin },
  });

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(120);
    doc.text(`${GENERATED_BY_NOTICE}  Page ${i} of ${pages}`, margin, 792 - 20);
  }

  return Buffer.from(doc.output('arraybuffer'));
}
