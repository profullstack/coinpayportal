/**
 * Report artifacts, all derived from one canonical dataset.
 *
 * The dataset is what the report IS; CSV, HTML and PDF are views of it. No
 * renderer computes a total — every figure it prints was summed exactly
 * upstream (in Postgres and re-checked in `decimal.ts`) and arrives here as
 * a decimal string. A renderer that disagreed with the JSON would be a bug
 * in the renderer, never a second opinion.
 *
 * This module has no server-only import so the text formats can be tested
 * as pure functions; the PDF renderer loads jsPDF lazily.
 */

